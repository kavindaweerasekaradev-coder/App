const PRICE = { ultra: 135, dc: 118, ac: 84 }

function c(type: ConnectorType, powerKw: number, total: number, available: number): Connector {
  const pricePerKwh = type === 'Type 2' ? PRICE.ac : powerKw >= 100 ? PRICE.ultra : PRICE.dc
  return { type, powerKw, total, available, pricePerKwh }
}

