def product_card(p, h):
    e, ARROW = h["e"], h["ARROW"]
    chips = "".join(f"<li>{e(c)}</li>" for c in p["chips"])
    links = "".join(
        f'<a class="live__go" href="{e(u)}" target="_blank" rel="noopener" aria-label="{e(aria)}">{e(label)}<span class="live__go-icon"></span></a>'
        for label, u, aria in p["links"])
    role = (f"<p>{e(p['role'])}</p>" if p.get("role") else "") + (
        "<ul>" + "".join(f"<li>{e(x)}</li>" for x in p["role_points"]) + "</ul>" if p.get("role_points") else "")
    cs = ""
    badge = ""
    if p.get("case_study"):
        badge = '<span class="live__badge">Case study</span>'
        cs = (f'<a class="btn btn--lime btn--arrow btn--sm live__cs" href="{e(p["case_study"])}">Read the case study'
              f'<span class="btn__circle">{ARROW}</span></a>')
    fill = " live__logo--fill" if p.get("logo_fill") else ""
    return f"""          <article class="live__card{' live__card--cs' if cs else ''} reveal" id="{e(p['slug'])}">
            <div class="live__top">
              <span class="live__logo{fill}"><img src="../{e(p['logo'])}" alt="{e(p['name'])} logo" width="56" height="56" loading="lazy" decoding="async" /></span>
              <span class="live__status"><i aria-hidden="true"></i>Live</span>{badge}
            </div>
            <p class="live__cat">{e(p['category'])}</p>
            <h2 class="live__name">{e(p['name'])}</h2>
            <p class="live__text">{e(p['text'])}</p>
            <ul class="live__chips" aria-label="Platforms">{chips}</ul>
            <div class="live__links">{cs}{links}</div>
            <div class="live__foot">
              <details class="live__role"><summary>My role <span class="live__plus"></span></summary><div class="live__role-body">{role}</div></details>
            </div>
          </article>"""


