OUT = os.path.join(ROOT, "shipped")


def write_all(version, h):
    with open(os.path.join(ROOT, "assets", "data", "shipped.json"), encoding="utf-8") as f:
        data = json.load(f)
    os.makedirs(OUT, exist_ok=True)
    pages = {
        "index.html": shipped_page(data, version, h),
        "readyme.html": readyme_page(data, version, h),
    }
    for name, html in pages.items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write(html)
        print("wrote", os.path.relpath(os.path.join(OUT, name), ROOT))


